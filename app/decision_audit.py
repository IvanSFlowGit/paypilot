"""Append-only audit trail for dunning decisions.

Two backends behind one two-method interface (``record`` and ``for_invoice``):

* :class:`SqliteDecisionAudit` - the FastAPI app on Fly, and every offline test.
* :class:`PostgresDecisionAudit` - the Lambda slice, against RDS. ``pg8000`` is
  imported lazily so the offline suite never needs it installed.

A row carries the invoice id, the rule that fired, the validated input and the
decision. No name, no email, no card: the decision input does not accept them,
so they cannot reach this table.

There is no update or delete method on either backend.

``decision_outcomes`` closes the loop, and it is a SEPARATE table for exactly
that reason. Until it existed, the decision API recorded what it decided and
never learned whether it worked: the stateful webhook path marks a failure row
recovered on ``invoice.paid`` (app/loop.py), and the stateless path a client
actually integrates had no equivalent, so the recovery-rate claim was true of
the demo and unmeasurable where it is sold. The obvious fix - an ``outcome``
column on ``decision_audit`` - needs an UPDATE, and the sentence above is a
guarantee rather than an observation, so the outcome is appended beside the
decision instead of mutating it. Both tables stay append-only and a disputed
number can still be traced to the rows that produced it.
"""

from __future__ import annotations

import contextlib
import json
import os
import sqlite3
import ssl
import threading
import uuid
from pathlib import Path

DECISION_AUDIT_DB_ENV = "PAYPILOT_DECISION_AUDIT_DB_PATH"

# Kept portable between SQLite and Postgres on purpose: text ids generated by
# the application, ISO-8601 timestamps as text, JSON as text. The Postgres copy
# is app/decision_schema.sql and tests/test_decision.py asserts the two agree.
SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS decision_audit (
    id          TEXT PRIMARY KEY,
    invoice_id  TEXT NOT NULL,
    client_id   TEXT NOT NULL DEFAULT '',
    rule_fired  TEXT NOT NULL,
    decided_at  TEXT NOT NULL,
    input       TEXT NOT NULL,
    decision    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_decision_audit_invoice
    ON decision_audit (invoice_id, decided_at);

CREATE TABLE IF NOT EXISTS decision_outcomes (
    id          TEXT PRIMARY KEY,
    invoice_id  TEXT NOT NULL,
    client_id   TEXT NOT NULL,
    outcome     TEXT NOT NULL,
    reported_at TEXT NOT NULL,
    report_key  TEXT NOT NULL,
    source      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_decision_outcomes_invoice
    ON decision_outcomes (invoice_id, client_id, reported_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_decision_outcomes_report_key
    ON decision_outcomes (client_id, report_key);
"""

#: Most rows a lookup returns. An invoice with more decisions than this is
#: being hammered, and the newest rows are the ones worth reading.
LOOKUP_LIMIT = 50

#: The two outcomes a caller may REPORT. ``unknown`` is deliberately not one of
#: them: it is what :func:`outcome_for` returns when no row exists, so nobody
#: has to write a row meaning "nothing happened" and an absent report cannot be
#: confused with a negative one. Storing three values would have made those two
#: states indistinguishable, which is the whole defect this table exists to fix.
OUTCOME_PAID = "paid"
OUTCOME_NOT_PAID = "not_paid"
OUTCOME_UNKNOWN = "unknown"
REPORTABLE_OUTCOMES = frozenset({OUTCOME_PAID, OUTCOME_NOT_PAID})


def _row(audit_id: str, decision: dict) -> tuple:
    # decision["client_id"] is read without a default ON PURPOSE. A missing client id is a
    # programming error on the write path, and defaulting it to the empty string would write
    # an unattributable row that the filter then hides from everybody, which looks identical
    # to a row that was never written.
    return (
        audit_id,
        decision["invoice_id"],
        decision["client_id"],
        decision["rule_fired"],
        decision["decided_at"],
        json.dumps(decision["input"], sort_keys=True),
        json.dumps(decision, sort_keys=True),
    )


def _outcome_row(row_id: str, outcome: dict) -> tuple:
    # Every field read without a default, for the reason _row gives: a missing
    # client id or report key here is a programming error on the write path, and
    # defaulting it writes a row the filter then hides from everybody.
    return (
        row_id,
        outcome["invoice_id"],
        outcome["client_id"],
        outcome["outcome"],
        outcome["reported_at"],
        outcome["report_key"],
        outcome["source"],
    )


def _as_outcome(row) -> dict:
    """The resolved outcome. No row means ``unknown``, which is not ``not_paid``.

    A caller that cannot tell "nobody has told us" from "we were told it did not
    pay" will divide by the wrong denominator, so the two are different answers
    and the second one carries a timestamp while the first cannot.
    """
    if row is None:
        return {"outcome": OUTCOME_UNKNOWN, "reported_at": None, "source": None}
    return {"outcome": row[0], "reported_at": row[1], "source": row[2]}


def _counts(decided: int, rows) -> dict:
    counts = {OUTCOME_PAID: 0, OUTCOME_NOT_PAID: 0}
    for outcome, n in rows:
        if outcome in counts:
            counts[outcome] = int(n)
    reported = counts[OUTCOME_PAID] + counts[OUTCOME_NOT_PAID]
    return {
        "decided": int(decided),
        OUTCOME_PAID: counts[OUTCOME_PAID],
        OUTCOME_NOT_PAID: counts[OUTCOME_NOT_PAID],
        # Decided and never reported on. Reported outcomes cannot exceed decided
        # invoices (an outcome needs a decision first), so this cannot go negative
        # while that rule holds; max() is here so a future path that breaks the
        # rule reports zero rather than a negative count nobody would believe.
        OUTCOME_UNKNOWN: max(0, int(decided) - reported),
    }


def _as_record(audit_id, rule_fired, decided_at, decision_json) -> dict:
    return {
        "audit_id": audit_id,
        "rule_fired": rule_fired,
        "decided_at": decided_at,
        "decision": json.loads(decision_json),
    }


class SqliteDecisionAudit:
    """SQLite decision audit. ``:memory:`` unless a path or the env var is set."""

    def __init__(self, path: str | Path | None = None) -> None:
        self.path = str(path or os.getenv(DECISION_AUDIT_DB_ENV) or ":memory:")
        if self.path != ":memory:":
            Path(self.path).parent.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()
        self._conn = sqlite3.connect(self.path, check_same_thread=False)
        self._conn.executescript(SQLITE_SCHEMA)
        # CREATE TABLE IF NOT EXISTS DOES NOT ADD A COLUMN to a database that already
        # exists, and SQLite has no ADD COLUMN IF NOT EXISTS, so a file written before
        # client_id existed would keep working with no column to filter on while a fresh
        # one got it and the suite stayed green. Postgres carries the same migration as an
        # idempotent ALTER in decision_schema.sql.
        cols = {r[1] for r in self._conn.execute("PRAGMA table_info(decision_audit)")}
        if "client_id" not in cols:
            self._conn.execute(
                "ALTER TABLE decision_audit ADD COLUMN client_id TEXT NOT NULL DEFAULT ''")
        self._conn.commit()

    def export_client(self, client_id: str) -> dict:
        """Every decision and outcome row of one client, for the offboarding export."""
        if not client_id:
            raise ValueError("client_id required")
        with self._lock:
            self._conn.row_factory = sqlite3.Row
            try:
                audit = [dict(r) for r in self._conn.execute(
                    "SELECT * FROM decision_audit WHERE client_id = ? ORDER BY decided_at",
                    (client_id,))]
                outcomes = [dict(r) for r in self._conn.execute(
                    "SELECT * FROM decision_outcomes WHERE client_id = ? ORDER BY reported_at",
                    (client_id,))]
            finally:
                self._conn.row_factory = None
        return {"decision_audit": audit, "decision_outcomes": outcomes}

    def erase_client(self, client_id: str) -> dict:
        """Delete every decision and outcome row of one client (tenant offboarding)."""
        if not client_id:
            raise ValueError("client_id required")
        with self._lock:
            a = self._conn.execute("DELETE FROM decision_audit WHERE client_id = ?", (client_id,))
            o = self._conn.execute("DELETE FROM decision_outcomes WHERE client_id = ?", (client_id,))
            self._conn.commit()
        return {"decision_audit": a.rowcount, "decision_outcomes": o.rowcount}

    def record(self, decision: dict) -> str:
        audit_id = uuid.uuid4().hex
        with self._lock:
            self._conn.execute(
                "INSERT INTO decision_audit "
                "(id, invoice_id, client_id, rule_fired, decided_at, input, decision) "
                "VALUES (?, ?, ?, ?, ?, ?, ?)",
                _row(audit_id, decision),
            )
            self._conn.commit()
        return audit_id

    def for_invoice(self, invoice_id: str, client_id: str) -> list[dict]:
        # client_id is REQUIRED, not defaulted. A lookup with no client would otherwise see
        # every client's rows, and the invoice id is chosen by the caller, so one client only
        # has to guess another's to read it.
        with self._lock:
            rows = self._conn.execute(
                "SELECT id, rule_fired, decided_at, decision FROM decision_audit "
                "WHERE invoice_id = ? AND client_id = ? "
                "ORDER BY decided_at DESC, rowid DESC LIMIT ?",
                (invoice_id, client_id, LOOKUP_LIMIT),
            ).fetchall()
        return [_as_record(*r) for r in rows]

    def has_decision(self, invoice_id: str, client_id: str) -> bool:
        # client_id is in the predicate, so this answers "have WE decided on this
        # invoice for THIS client" and never "does this invoice exist". One client
        # probing another's invoice ids gets the same answer as for an id nobody
        # has ever seen, which is the property the 404 on for_invoice already has.
        with self._lock:
            row = self._conn.execute(
                "SELECT 1 FROM decision_audit WHERE invoice_id = ? AND client_id = ? LIMIT 1",
                (invoice_id, client_id),
            ).fetchone()
        return row is not None

    def record_outcome(self, outcome_row: dict) -> tuple[str, bool]:
        """Append one outcome report. Returns ``(id, stored)``.

        ``stored`` is False when the report key has been seen for this client
        before, which makes a redelivery a no-op rather than a second row. The
        caller is told which happened instead of both looking like success,
        because a retried POST that silently counted twice is how a recovery
        rate inflates. ``INSERT OR IGNORE`` only ignores the unique-index
        collision; a malformed row still raises.
        """
        row_id = uuid.uuid4().hex
        with self._lock:
            cur = self._conn.execute(
                "INSERT OR IGNORE INTO decision_outcomes "
                "(id, invoice_id, client_id, outcome, reported_at, report_key, source) "
                "VALUES (?, ?, ?, ?, ?, ?, ?)",
                _outcome_row(row_id, outcome_row),
            )
            self._conn.commit()
            if cur.rowcount:
                return row_id, True
            existing = self._conn.execute(
                "SELECT id FROM decision_outcomes WHERE client_id = ? AND report_key = ?",
                (outcome_row["client_id"], outcome_row["report_key"]),
            ).fetchone()
        return (existing[0] if existing else row_id), False

    def outcome_for(self, invoice_id: str, client_id: str) -> dict:
        with self._lock:
            row = self._conn.execute(
                "SELECT outcome, reported_at, source FROM decision_outcomes "
                "WHERE invoice_id = ? AND client_id = ? "
                "ORDER BY reported_at DESC, rowid DESC LIMIT 1",
                (invoice_id, client_id),
            ).fetchone()
        return _as_outcome(row)

    def outcome_counts(self, client_id: str) -> dict:
        """Latest reported outcome per invoice, counted. Decided-but-unreported
        invoices are counted as ``unknown`` rather than dropped."""
        with self._lock:
            decided = self._conn.execute(
                "SELECT COUNT(DISTINCT invoice_id) FROM decision_audit WHERE client_id = ?",
                (client_id,),
            ).fetchone()[0]
            rows = self._conn.execute(
                # The latest report per invoice, then grouped. Picking the row with
                # MAX(reported_at) per invoice is why this is not a plain GROUP BY:
                # an invoice reported not_paid and later paid must count once, as paid.
                "SELECT outcome, COUNT(*) FROM ("
                "  SELECT invoice_id, outcome,"
                "         ROW_NUMBER() OVER ("
                "             PARTITION BY invoice_id ORDER BY reported_at DESC, rowid DESC"
                "         ) AS rn"
                "  FROM decision_outcomes WHERE client_id = ?"
                ") WHERE rn = 1 GROUP BY outcome",
                (client_id,),
            ).fetchall()
        return _counts(decided, rows)


def set_client(conn, client_id: str) -> None:
    """Declare the tenant for the CURRENT TRANSACTION only.

    is_local = true is the whole safety property: the value dies at COMMIT or
    ROLLBACK and cannot be read by anything that reuses this connection.

    It lives in this module rather than in the bootstrap that first needed it
    because the bootstrap imports this file: two copies would be the one home
    rule broken on the one statement whose wording is the safety property.
    """
    conn.run("SELECT set_config('paypilot.client_id', :client_id, true)", client_id=client_id)


class PostgresDecisionAudit:
    """Postgres decision audit for the Lambda slice.

    Connection settings come from the standard libpq names (``PGHOST``,
    ``PGPORT``, ``PGDATABASE``, ``PGUSER``, ``PGPASSWORD``). TLS is required and
    the server certificate is verified against ``PGSSLROOTCERT`` (the RDS CA
    bundle shipped in the deployment package); there is no unverified fallback.

    One connection is held per warm Lambda container and re-opened once if it
    has gone stale between invocations.
    """

    def __init__(self, env: dict | None = None) -> None:
        self._env = env if env is not None else os.environ
        self._conn = None

    def _connect(self):
        return open_connection(self._env)

    def _drop_conn(self) -> None:
        try:
            if self._conn is not None:
                self._conn.close()
        except Exception:  # noqa: BLE001 - a dead connection must not mask the verdict
            pass
        self._conn = None

    @contextlib.contextmanager
    def _as_client(self, client_id: str):
        """Open a transaction that declares the tenant, and yield a run function.

        EVERY TENANT-SCOPED STATEMENT GOES THROUGH HERE, because the row level
        security policy reads ``current_setting('paypilot.client_id')`` and a
        statement that runs without it reads nothing at all: the policy's
        ``nullif`` maps the unset variable to NULL, and ``client_id = NULL`` is
        NULL rather than true. So a caller that forgets this wrapper fails
        closed and loudly, which is the direction a missing predicate did not
        fail in before.

        ``is_local => true`` is the whole safety property and it is not a
        detail: one connection is held per warm Lambda container, so a
        session-scoped setting would leak one tenant's id into the next
        invocation, which is worse than having no policy at all. A local
        setting dies at COMMIT or ROLLBACK.

        The single reconnect retry covers the BEGIN rather than the body. That
        is where a connection frozen between invocations now fails first, so
        the coverage ``_run_unscoped`` had is preserved rather than lost; and a
        failure inside the body is not retried, because a context manager
        cannot re-run its caller's block and silently repeating half a
        transaction is worse than a 503.
        """
        for attempt in (1, 2):
            try:
                if self._conn is None:
                    self._conn = self._connect()
                self._conn.run("BEGIN")
                set_client(self._conn, client_id)
                break
            except Exception:
                self._drop_conn()
                if attempt == 2:
                    raise
        conn = self._conn
        try:
            yield lambda sql, **params: conn.run(sql, **params)
        except Exception:
            try:
                conn.run("ROLLBACK")
            except Exception:  # noqa: BLE001 - the original error is the finding
                self._drop_conn()
            raise
        conn.run("COMMIT")

    def _run_unscoped(self, sql: str, **params):
        """Run OUTSIDE any tenant scope. Schema only: no policy applies to DDL.

        Named for what it does not do, because the dangerous version of this
        method is the one whose name does not say that a tenant is missing.
        """
        for attempt in (1, 2):
            try:
                if self._conn is None:
                    self._conn = self._connect()
                return self._conn.run(sql, **params)
            except Exception:
                # A stale connection from a frozen container fails on first use.
                # Drop it and try exactly once more; a second failure propagates
                # and the caller fails closed. Retrying the INSERT is safe because
                # the row id is generated before the first attempt: if that
                # attempt did land, the retry hits the primary key and fails,
                # so the worst case is a 503 for a recorded row, never two rows.
                try:
                    if self._conn is not None:
                        self._conn.close()
                except Exception:  # noqa: BLE001
                    pass
                self._conn = None
                if attempt == 2:
                    raise
        raise AssertionError("unreachable")

    def record(self, decision: dict) -> str:
        audit_id = uuid.uuid4().hex
        values = _row(audit_id, decision)
        with self._as_client(values[2]) as run:
            run(
                "INSERT INTO decision_audit "
                "(id, invoice_id, client_id, rule_fired, decided_at, input, decision) "
                "VALUES (:id, :invoice_id, :client_id, :rule_fired, :decided_at, "
                ":input, :decision)",
                id=values[0],
                invoice_id=values[1],
                client_id=values[2],
                rule_fired=values[3],
                decided_at=values[4],
                input=values[5],
                decision=values[6],
            )
        return audit_id

    def for_invoice(self, invoice_id: str, client_id: str) -> list[dict]:
        # Newest first by decided_at (millisecond precision). Two decisions in the
        # same millisecond have no defined order here; SQLite breaks the tie by rowid.
        # client_id is REQUIRED on this path too. A filter on one store and not the other
        # is worse than none: it looks identical from outside and is wrong on one of them.
        with self._as_client(client_id) as run:
            rows = run(
                "SELECT id, rule_fired, decided_at, decision FROM decision_audit "
                "WHERE invoice_id = :invoice_id AND client_id = :client_id "
                "ORDER BY decided_at DESC LIMIT :limit",
                invoice_id=invoice_id,
                client_id=client_id,
                limit=LOOKUP_LIMIT,
            )
        return [_as_record(*r) for r in rows]

    def has_decision(self, invoice_id: str, client_id: str) -> bool:
        with self._as_client(client_id) as run:
            rows = run(
                "SELECT 1 FROM decision_audit "
                "WHERE invoice_id = :invoice_id AND client_id = :client_id LIMIT 1",
                invoice_id=invoice_id,
                client_id=client_id,
            )
        return bool(rows)

    def record_outcome(self, outcome_row: dict) -> tuple[str, bool]:
        # RETURNING id rather than a row count: ON CONFLICT DO NOTHING returns no
        # row when the report key was already present, so the same two states the
        # SQLite path reports are readable here without asking for an affected-row
        # count, which pg8000 does not surface through run().
        row_id = uuid.uuid4().hex
        values = _outcome_row(row_id, outcome_row)
        # Both statements run in ONE transaction, which is a correctness gain on
        # top of the tenant scope: the read-back that resolves a duplicate now
        # cannot see a different snapshot from the insert that lost the race.
        with self._as_client(values[2]) as run:
            rows = run(
                "INSERT INTO decision_outcomes "
                "(id, invoice_id, client_id, outcome, reported_at, report_key, "
                "source) VALUES (:id, :invoice_id, :client_id, :outcome, "
                ":reported_at, :report_key, :source) "
                "ON CONFLICT (client_id, report_key) DO NOTHING RETURNING id",
                id=values[0],
                invoice_id=values[1],
                client_id=values[2],
                outcome=values[3],
                reported_at=values[4],
                report_key=values[5],
                source=values[6],
            )
            if rows:
                return rows[0][0], True
            existing = run(
                "SELECT id FROM decision_outcomes "
                "WHERE client_id = :client_id AND report_key = :report_key",
                client_id=outcome_row["client_id"],
                report_key=outcome_row["report_key"],
            )
        return (existing[0][0] if existing else row_id), False

    def outcome_for(self, invoice_id: str, client_id: str) -> dict:
        with self._as_client(client_id) as run:
            rows = run(
                "SELECT outcome, reported_at, source FROM decision_outcomes "
                "WHERE invoice_id = :invoice_id AND client_id = :client_id "
                "ORDER BY reported_at DESC LIMIT 1",
                invoice_id=invoice_id,
                client_id=client_id,
            )
        return _as_outcome(rows[0] if rows else None)

    def outcome_counts(self, client_id: str) -> dict:
        with self._as_client(client_id) as run:
            decided = run(
                "SELECT COUNT(DISTINCT invoice_id) FROM decision_audit "
                "WHERE client_id = :client_id",
                client_id=client_id,
            )
            rows = run(
                "SELECT outcome, COUNT(*) FROM ("
                "  SELECT invoice_id, outcome,"
                "         ROW_NUMBER() OVER ("
                "             PARTITION BY invoice_id ORDER BY reported_at DESC"
                "         ) AS rn"
                "  FROM decision_outcomes WHERE client_id = :client_id"
                ") latest WHERE rn = 1 GROUP BY outcome",
                client_id=client_id,
            )
        return _counts(decided[0][0] if decided else 0, rows)

    def ensure_schema(self, schema_sql: str) -> None:
        """Apply the schema. Idempotent (every statement is IF NOT EXISTS)."""
        for statement in split_sql_statements(schema_sql):
            self._run_unscoped(statement)


def open_connection(env):
    """Open a verified-TLS pg8000 connection from libpq-style settings in ``env``.

    Shared by the decision audit and the bootstrap function, so both refuse an
    unverified connection the same way.
    """
    cafile = env.get("PGSSLROOTCERT")
    if not cafile:
        raise RuntimeError("PGSSLROOTCERT is not set; refusing an unverified TLS connection")

    import pg8000.native  # lazy: not needed by the offline suite

    context = ssl.create_default_context(cafile=cafile)
    return pg8000.native.Connection(
        user=env["PGUSER"],
        password=env["PGPASSWORD"],
        host=env["PGHOST"],
        port=int(env.get("PGPORT", "5432")),
        database=env["PGDATABASE"],
        ssl_context=context,
        timeout=5,
    )


def split_sql_statements(schema_sql: str) -> list[str]:
    """Split a schema file into statements, respecting single-quoted literals.

    Splitting on ``;`` before removing comments sent a comment fragment to
    Postgres as a statement: the schema header's prose contained a semicolon.
    Found against a real Postgres, not by the offline suite.

    THE EARLIER VERSION STRIPPED ``--`` LINE-WISE AND THEN SPLIT ON ``;``,
    justified in its own docstring by "the schema has no string literals, so
    a ``--`` is always a comment here". That was true and it stopped being
    true the moment row level security arrived, because a policy has to name
    its session variable and that is a literal. Measured before changing it:
    a ``;`` inside a literal split one statement into two, and a ``--``
    inside one truncated the statement and dropped the rest in silence.
    Neither raises, so Postgres would receive a fragment and the loss would
    look like a schema that simply did not have that policy.

    So the invariant is now enforced rather than assumed: quotes are tracked,
    ``''`` is read as an escaped quote inside a literal, and a ``$`` dollar
    quote is REFUSED rather than mis-split, because this parser does not
    implement dollar quoting and silently mangling one is worse than saying
    so. Comments and separators outside literals behave exactly as before.
    """
    if "$$" in schema_sql:
        raise ValueError(
            "the schema contains a dollar-quoted block and this splitter does "
            "not implement dollar quoting. It would mis-split it silently, so "
            "it refuses instead: add dollar-quote handling or keep the schema "
            "free of them."
        )

    out: list[str] = []
    buf: list[str] = []
    in_literal = False
    i = 0
    n = len(schema_sql)
    while i < n:
        ch = schema_sql[i]
        if in_literal:
            # NO SPECIAL CASE FOR '' AND THAT IS MEASURED RATHER THAN ASSUMED.
            # One was written here, on the usual reasoning that '' is an
            # escaped quote inside a literal and must not close it. Mutating
            # it away reddened NOTHING, so the two were compared directly
            # across 255,987 inputs: exhaustive over every string up to six
            # characters drawn from the hazardous alphabet (quote, semicolon,
            # dash, newline, letters) plus 200,000 random longer ones. ZERO
            # divergences, because '' is two quotes and therefore two
            # toggles, so parity already leaves the parser inside the literal
            # exactly where the escape rule would. The branch was noise paid
            # for on every character, and the test that covers it asserts the
            # property that matters, a ; inside the literal staying put.
            if ch == "'":
                in_literal = False
            buf.append(ch)
            i += 1
            continue
        if ch == "'":
            in_literal = True
            buf.append(ch)
            i += 1
            continue
        if ch == "-" and schema_sql.startswith("--", i):
            # Comment to end of line, outside any literal.
            nl = schema_sql.find("\n", i)
            if nl == -1:
                break
            i = nl
            continue
        if ch == ";":
            out.append("".join(buf))
            buf = []
            i += 1
            continue
        buf.append(ch)
        i += 1

    if in_literal:
        raise ValueError(
            "the schema ends inside an unterminated string literal, so the "
            "statements cannot be separated. Refusing rather than sending a "
            "fragment to Postgres."
        )
    out.append("".join(buf))
    return [s.strip() for s in out if s.strip()]
