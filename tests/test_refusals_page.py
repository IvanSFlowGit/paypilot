"""app/static/refusals-sample.html must be exactly what a fresh walk renders, and be served.

Mirrors tests/test_ach_page.py. The page is generated by RUNNING the walk, so a refusal gate
that stops refusing turns the page stale and the build red, instead of a visitor reading a
claim the code no longer makes. The route is exercised too, because a correct file that
nothing serves is a file.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from app.api import app

_PATH = Path(__file__).resolve().parents[1] / "scripts" / "render_refusals_page.py"
_spec = importlib.util.spec_from_file_location("render_refusals_page", _PATH)
mod = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mod)


def test_committed_page_matches_a_fresh_run():
    assert mod.OUT.read_text(encoding="utf-8") == mod.render(), (
        "app/static/refusals-sample.html is stale: run python scripts/render_refusals_page.py"
    )


def test_rendering_twice_is_identical():
    assert mod.render() == mod.render()


def test_the_page_lists_every_expected_gate_and_marks_both_controls():
    page = mod.OUT.read_text(encoding="utf-8")
    for gate in ("input_validated", "rule_lookup", "recipient_allowlist", "output_guard"):
        assert f"<code>{gate}</code>" in page, gate
    assert page.count('<td class="must-not">must not appear</td>') == 2
    # Seven steps and five view rows plus two header rows.
    assert page.count("<tr>") == 14


def test_the_page_says_its_data_is_invented_and_names_what_it_does_not_show():
    page = mod.OUT.read_text(encoding="utf-8").lower()
    assert "invented" in page
    assert "not switched on for this public deployment" in page
    assert "postgres" in page


def test_the_page_carries_no_comment_a_visitor_could_read():
    page = mod.OUT.read_text(encoding="utf-8")
    assert "<!--" not in page and "/*" not in page


def test_the_page_carries_no_real_looking_identifier():
    page = mod.OUT.read_text(encoding="utf-8")
    assert "@" not in page
    assert "re_" not in page.replace("require", "").replace("record", "")
    assert page.count("SYN-") >= 4


def test_the_page_is_served_and_public():
    response = TestClient(app).get("/refusals-sample")
    assert response.status_code == 200
    assert "Every refusal gate" in response.text


def test_the_page_is_in_the_sitemap():
    sitemap = (Path(__file__).resolve().parents[1] / "app" / "static" / "sitemap.xml").read_text(encoding="utf-8")
    assert "https://paypilot.fly.dev/refusals-sample" in sitemap


def test_a_gate_that_stops_refusing_makes_the_renderer_refuse_to_render(monkeypatch):
    from app import refusals

    monkeypatch.delitem(refusals.REASON_GATES, "recipient_not_allowlisted")
    with pytest.raises(SystemExit, match="refusing to render"):
        mod.render()
