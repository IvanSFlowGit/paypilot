"""Render app/static/refusals-sample.html by RUNNING scripts/refusal_walk.py.

The page is what that walk produced, not a description of it: this script calls
``refusal_walk.collect()`` and prints the steps and the refusal view it returned. A test
re-renders the page and fails if the committed file differs, so a gate that stops refusing
turns the page stale and the build red instead of leaving a visitor reading a claim the code
no longer makes. It also refuses to render at all when the walk's own expectations fail.

Every row is invented. Timestamps and ids are left out so the output is the same on every run.

No comments are emitted into the HTML or the CSS (scripts/lint_style.py fails the build on a
comment in a public asset).

    python scripts/render_refusals_page.py
"""

from __future__ import annotations

import html
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "app" / "static" / "refusals-sample.html"
URL = "https://paypilot.fly.dev/refusals-sample"
REPO = "https://github.com/IvanSFlowGit/paypilot"


def _load(name: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_walk = _load("refusal_walk")
STYLE = _load("render_ach_page").STYLE + (
    "  td.must-not { color:var(--brand-2); font-weight:600; }\n"
    "  td.n { color:var(--brand-2); font-weight:700; }\n"
    "  .card { overflow-x:auto; }\n"
    "  .card table { min-width:560px; }\n"
    "  video { display:block; width:100%; height:auto; border-radius:10px; background:#000; }\n"
)


def _e(text: str) -> str:
    return html.escape(text, quote=False)


def render() -> str:
    result = _walk.collect()
    if result["missing"] or result["unexpected"] or result["unclassified"]:
        raise SystemExit(
            "refusing to render: the walk's own expectations failed "
            f"(missing={result['missing']}, unexpected={result['unexpected']}, "
            f"unclassified={result['unclassified']})"
        )
    n_steps = len(result["steps"])
    n_controls = sum(1 for s in result["steps"] if s["control"])
    n_rows = len(result["rows"])

    step_rows = "\n".join(
        f'      <tr><td class="n">{s["n"]}</td><td>{_e(s["what"])}</td><td><code>{_e(s["outcome"])}</code></td>'
        f'<td{" class=" + chr(34) + "must-not" + chr(34) if s["control"] else ""}>'
        f'{"must not appear" if s["control"] else "appears"}</td></tr>'
        for s in result["steps"]
    )
    view_rows = "\n".join(
        f"      <tr><td><code>{_e(r['source'])}</code></td><td><code>{_e(r['gate'])}</code></td>"
        f"<td><code>{_e(r['reason'])}</code></td><td>{_e(r['invoice_id']) or '-'}</td></tr>"
        for r in result["rows"]
    )
    sources = ", ".join(f"<code>{_e(k)}: {_e(v)}</code>" for k, v in result["sources"].items())

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<title>PayPilot - Every refusal gate, run on invented data</title>
<meta name="description" content="{n_steps} invented requests through the real code: {n_rows} refusals recorded under the gate that refused, and {n_controls} controls that must not appear. Generated by running the code." />
<link rel="canonical" href="{URL}" />
<meta name="robots" content="index,follow" />
<meta name="theme-color" content="#0b1120" />
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Crect width='32' height='32' rx='8' fill='%234f8cff'/%3E%3C/svg%3E" />
<style>
  {STYLE}</style>
</head>
<body>
<div class="wrap">
  <header class="top">
    <a class="logo" href="/" style="color:var(--ink)"><span class="mark">P</span> PayPilot</a>
    <nav>
      <a href="/">Demo</a>
      <a href="/ach-returns">ACH returns</a>
      <a href="/pricing">Pricing</a>
      <a href="{REPO}" target="_blank" rel="noopener">Source</a>
    </nav>
  </header>

  <span class="note">Invented data, run by the code on this page's source</span>
  <h1>Every refusal gate, <span class="grad">on one screen.</span></h1>
  <p class="lede">
    {n_steps} synthetic requests go through the real code paths. {n_rows} of them are refused,
    and each lands in the refusal view under the gate that refused it. {n_controls} are not
    refusals and must not appear: a decision that matched a rule, and a provider that failed.
  </p>

  <h2>Watch it</h2>
  <div class="card">
    <video controls preload="metadata" playsinline width="100%" poster="/static/refusals-walkthrough-poster.jpg" aria-label="A 29 second silent scroll through this page: the requests, the refusal view, the controls and the limits">
      <source src="/static/refusals-walkthrough.mp4" type="video/mp4" />
    </video>
    <p style="margin:12px 0 0; color:var(--muted); font-size:14px;">
      29 seconds, no sound. A recording of this page, scrolled top to bottom. It is not a recording of the code running; the tables below are what the code produced.
    </p>
  </div>

  <h2>What was sent</h2>
  <div class="card">
    <table>
      <thead>
      <tr><th>#</th><th>Request</th><th>What the system did</th><th>In the view</th></tr>
      </thead>
      <tbody>
{step_rows}
      </tbody>
    </table>
  </div>

  <h2>What the refusal view then lists</h2>
  <p>
    This is what <code>GET /refusals</code> returns for these requests: every refusal, with the
    store it came from and the gate that refused it. Sources read: {sources}.
  </p>
  <div class="card accent">
    <table>
      <thead>
      <tr><th>Store</th><th>Gate</th><th>Reason</th><th>Invoice</th></tr>
      </thead>
      <tbody>
{view_rows}
      </tbody>
    </table>
  </div>

  <h2>Why the controls matter</h2>
  <p>
    A table of refusals proves nothing if it can be empty for the wrong reason, or full of things
    that are not refusals. So the run names the rows it expects and fails if one is missing or if
    either control shows up. A provider that fails is a failure, not a refusal: nobody decided
    anything. A decision that matched a rule is not a refusal either. Both are absent above, and
    the build breaks if that stops being true.
  </p>

  <h2>What this page does not claim</h2>
  <ul class="disclaims">
    <li>Every request and invoice id is invented. Nothing here is the live app's data, and the live
      refusal view is behind an admin token.</li>
    <li>The run uses a local SQLite store and an in-memory event log. The event log is optional and
      is not switched on for this public deployment, so on the live app a draft the guard replaced
      would not appear in the view; it is shown here to show the shape.</li>
    <li>It does not show the Postgres path, and it says nothing about how often any gate fires.</li>
  </ul>

  <a class="btn" href="{REPO}" target="_blank" rel="noopener">Read the source</a>

  <footer>
    This page is generated by <code>scripts/render_refusals_page.py</code>, which runs
    <code>scripts/refusal_walk.py</code>, and a test fails the build if the committed page and a
    fresh run disagree. Run it yourself with <code>make refusal-walk</code>. PayPilot is a portfolio
    project with no paying clients.
  </footer>
</div>
</body>
</html>
"""


def main() -> int:
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
